function parseHMS(s) { const [h, m, x] = s.trim().split(/\s+/).map(Number); return (h + m / 60 + x / 3600) * 15; }
function parseDMS(s) { const t = s.trim(); const neg = t.startsWith('-'); const [d, m, x] = t.replace(/^[+-]/, '').split(/\s+/).map(Number); return (neg ? -1 : 1) * (d + m / 60 + x / 3600); }

export function brightStars() {
  return BRIGHT.trim().split('\n').map((l) => { const [ra, dec, mag, bv] = l.split('|'); return { ra: parseHMS(ra), dec: parseDMS(dec), mag: +mag, bv: +bv }; });
}

// galactic north pole and centre (J2000, equatorial unit vectors)
const NGP = [-0.8676661, -0.1980764, 0.4559838], GC = [-0.0548755, -0.8734371, -0.4838350];

// rough star colour from B-V (linear RGB, max 1)
function bvColor(bv) {
  const t = Math.min(Math.max((bv + 0.3) / 2.1, 0), 1);
  const stops = [[0.62, 0.72, 1.0], [0.82, 0.88, 1.0], [1.0, 0.96, 0.9], [1.0, 0.82, 0.6], [1.0, 0.62, 0.38]];
  const f = t * (stops.length - 1), i = Math.min(Math.floor(f), stops.length - 2), u = f - i;
  return stops[i].map((c, k) => c + (stops[i + 1][k] - c) * u);
}

export function createStars(skyUniforms, { faint = 3600 } = {}) {
  const list = brightStars();
  const R = rng('stars').next;
  // faint procedural field: N(<m) ~ 10^(0.5 m), more stars toward the galactic plane
  const lo = Math.pow(10, 0.5 * 4.0), hi = Math.pow(10, 0.5 * 6.5);
  for (let n = 0; n < faint;) {
    const z = R() * 2 - 1, a = R() * Math.PI * 2, s = Math.sqrt(1 - z * z);
    const e = [s * Math.cos(a), s * Math.sin(a), z];
    const b = Math.asin(e[0] * NGP[0] + e[1] * NGP[1] + e[2] * NGP[2]);
    if (R() > 0.32 + 0.68 * Math.exp(-(b * b) / (0.22 * 0.22))) continue;
    const mag = Math.log10(lo + R() * (hi - lo)) / 0.5;
    const bv = Math.min(1.9, Math.max(-0.3, 0.55 + (R() + R() + R() - 1.5) * 0.7));
    list.push({ e, mag, bv });
    n++;
  }
  const N = list.length;
  const pos = new Float32Array(N * 3), col = new Float32Array(N * 4);
  for (let i = 0; i < N; i++) {
    const s = list[i];
    let e = s.e;
    if (!e) { const ra = (s.ra * Math.PI) / 180, de = (s.dec * Math.PI) / 180; e = [Math.cos(de) * Math.cos(ra), Math.cos(de) * Math.sin(ra), Math.sin(de)]; }
    pos.set(e, i * 3);
    const c = bvColor(s.bv);
    col.set([c[0], c[1], c[2], s.mag], i * 4);
  }
  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.BufferAttribute(pos, 3));
  geo.setAttribute('aCol', new THREE.BufferAttribute(col, 4));
  geo.boundingSphere = new THREE.Sphere(new THREE.Vector3(), 1e9);
  const mat = new THREE.ShaderMaterial({
    uniforms: {
      uEq: skyUniforms.uEq, uStarVis: skyUniforms.uStarVis, uStarGain: skyUniforms.uStarGain,
      uPxScale: { value: 1 },
    },
    vertexShader: /* glsl */ `
      attribute vec4 aCol;
      uniform mat3 uEq;
      uniform float uStarVis, uStarGain, uPxScale;
      varying vec3 vC;
      varying float vSize;
      void main(){
        vec3 d = normalize(uEq * position);
        // extinction toward the horizon (airmass ~ 1/sin alt), and nothing below it
        float alt = d.y;
        float am = 1.0 / max(alt + 0.025, 0.012);
        float ext = exp(-0.22 * (am - 1.0)) * smoothstep(-0.005, 0.03, alt);
        float flux = pow(10.0, -0.4 * (aCol.w - 1.0)) * ext;          // 1 at magnitude 1
        // fainter stars stay a little brighter than physical, so the sky reads as full but not noisy
        flux = pow(flux, 0.78) * uStarGain * uStarVis;
        vec3 c = mix(vec3(0.75, 0.8, 1.0), aCol.rgb, 0.8) * mix(vec3(1.0), vec3(1.0, 0.75, 0.55), 1.0 - ext);
        float size = clamp(2.6 + 1.1 * log2(1.0 + flux * 4.0), 2.6, 7.0) * uPxScale;
        // the point's total light, spread over its Gaussian footprint (sigma = size / 4)
        float sig = size * 0.25;
        vC = c * flux / (6.2832 * sig * sig);
        vSize = size;
        vec4 p = projectionMatrix * modelViewMatrix * vec4(d * 4500.0, 1.0);
        p.z = p.w * 0.99999;
        gl_Position = p;
        gl_PointSize = flux > 1e-4 ? size : 0.0;
      }`,
    fragmentShader: /* glsl */ `
      varying vec3 vC;
      varying float vSize;
      void main(){
        vec2 q = (gl_PointCoord - 0.5) * vSize;
        float sig = vSize * 0.25;
        float g = exp(-dot(q, q) / (2.0 * sig * sig));
        gl_FragColor = vec4(vC * g, 1.0);
      }`,
    transparent: false, depthWrite: false, depthTest: true, fog: false,
    blending: THREE.CustomBlending, blendEquation: THREE.AddEquation, blendSrc: THREE.OneFactor, blendDst: THREE.OneFactor,
  });
  const pts = new THREE.Points(geo, mat);
  pts.name = 'stars';
  pts.frustumCulled = false;
  pts.renderOrder = 1001;          // right after the sky dome (1000)
  pts.onBeforeRender = (r, s, cam) => { pts.position.copy(cam.position); pts.updateMatrixWorld(); };
  pts.userData.count = N;
  return pts;
}
