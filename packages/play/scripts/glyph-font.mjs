const DIGITS = '0123456789abcdefghijklmnopqrstuv';
/** The encoded font: 95 glyphs (code points 32-126), 9 base-32 digits each. */
export function encode(art = ART) {
  let s = '';
  for (let c = 32; c < 127; c++) {
    const rows = art[String.fromCharCode(c)];
    if (!rows) throw new Error('glyph-font: no glyph for ' + JSON.stringify(String.fromCharCode(c)));
    for (let r = 0; r < 9; r++) {
      const row = rows[r] || '.....';
      if (row.length !== 5) throw new Error(`glyph-font: ${JSON.stringify(String.fromCharCode(c))} row ${r} is not 5 wide`);
      let v = 0;
      for (let k = 0; k < 5; k++) v = v * 2 + (row[k] === '#' ? 1 : 0);
      s += DIGITS[v];
    }
  }
  return s;
}

