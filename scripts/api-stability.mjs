// Mirage original code. How much of the public API is promised: every name a package's entry point exports,
// classed by the docs/api.md row that describes it.
//
//   node scripts/api-stability.mjs            print the table
//   node scripts/api-stability.mjs --write    and rewrite the generated block of docs/STABILITY.md
//   node scripts/api-stability.mjs --json     the same as data (per package: stable, experimental, unclassified names)
//
// A name is looked up in its own package's section first: a table row whose first cell names it, then a row that
// mentions it in backticks (the options and helpers of the row's subject), then the same over the whole file. A
// name only prose mentions is "unclassified": by the rule in docs/api.md (anything not listed stable is not
// promised) it counts as experimental, and is listed so somebody gives it a row.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKGS = ['core', 'world', 'play', 'game', 'net'];
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** docs/api.md as { '@mirage/core': [{ head, level, text }] }: the table rows that carry a stability cell. */
export function apiRows(md) {
  const out = {}; let pkg = null;
  for (const line of md.split('\n')) {
    const h = /^## (@mirage\/[\w-]+)/.exec(line);
    if (h) { pkg = h[1]; out[pkg] = []; continue; }
    if (/^## /.test(line)) { pkg = null; continue; }
    const m = /^\|(.+?)\|\s*(stable|experimental)\s*\|(.*)\|\s*$/.exec(line);
    if (pkg && m) out[pkg].push({ head: m[1], level: m[2], text: m[3] });
  }
  return out;
}

/** 'stable' | 'experimental' | null for one export name of one package. */
export function classify(name, pkg, rows) {
  const word = new RegExp('(^|[^\\w$.])' + esc(name) + '([^\\w$]|$)'), ticked = new RegExp('`' + esc(name) + '[`(.\\s,]');
  const own = rows[pkg] || [], all = Object.values(rows).flat();
  for (const set of [own, all]) {
    const hit = set.find((r) => word.test(r.head)) || set.find((r) => ticked.test(r.text));
    if (hit) return hit.level;
  }
  return null;
}

export async function report() {
  const rows = apiRows(fs.readFileSync(path.join(ROOT, 'docs/api.md'), 'utf8')), out = [];
  for (const p of PKGS) {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'packages', p, 'package.json'), 'utf8'));
    const main = pkg.exports['.'], entry = typeof main === 'string' ? main : main.import || main.default;
    const mod = await import(pathToFileURL(path.join(ROOT, 'packages', p, entry)));
    const r = { name: pkg.name, version: pkg.version, subpaths: Object.keys(pkg.exports).length - 1, stable: [], experimental: [], unclassified: [] };
    for (const k of Object.keys(mod).sort()) r[classify(k, pkg.name, rows) || 'unclassified'].push(k);
    out.push(r);
  }
  return out;
}

export function table(rep) {
  const n = (k) => rep.reduce((s, r) => s + r[k].length, 0), tot = n('stable') + n('experimental') + n('unclassified');
  const pct = (a, b) => (b ? Math.round((100 * a) / b) + ' %' : '-');
  const lines = ['| package | exports | stable | experimental | not in a row | stable share | subpaths |', '|---|---|---|---|---|---|---|'];
  for (const r of rep) {
    const t = r.stable.length + r.experimental.length + r.unclassified.length;
    lines.push(`| \`${r.name}\` | ${t} | ${r.stable.length} | ${r.experimental.length} | ${r.unclassified.length} | ${pct(r.stable.length, t)} | ${r.subpaths} |`);
  }
  lines.push(`| **all** | **${tot}** | **${n('stable')}** | **${n('experimental')}** | **${n('unclassified')}** | **${pct(n('stable'), tot)}** | ${rep.reduce((s, r) => s + r.subpaths, 0)} |`);
  const loose = rep.filter((r) => r.unclassified.length).map((r) => `- \`${r.name}\`: ${r.unclassified.map((k) => '`' + k + '`').join(', ')}`);
  if (loose.length) lines.push('', 'Exported and mentioned in docs/api.md, but in no row with a stability cell (treated as experimental):', '', ...loose);
  return lines.join('\n');
}

const BEGIN = '<!-- generated by scripts/api-stability.mjs: do not edit by hand -->', END = '<!-- end generated -->';

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rep = await report();
  if (process.argv.includes('--json')) console.log(JSON.stringify(rep, null, 2));
  else {
    const t = table(rep); console.log(t);
    if (process.argv.includes('--write')) {
      const f = path.join(ROOT, 'docs/STABILITY.md'), md = fs.readFileSync(f, 'utf8'), a = md.indexOf(BEGIN), b = md.indexOf(END);
      if (a < 0 || b < a) { console.error('docs/STABILITY.md has no generated block'); process.exit(1); }
      fs.writeFileSync(f, md.slice(0, a) + BEGIN + '\n' + t + '\n' + md.slice(b));
      console.log('\nwrote docs/STABILITY.md');
    }
  }
}
